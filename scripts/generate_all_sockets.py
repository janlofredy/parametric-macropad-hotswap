import math
import struct
import time
import os

def interpolate(p1, p2, v1, v2):
    if abs(v2 - v1) < 1e-9:
        t = 0.5
    else:
        t = -v1 / (v2 - v1)
        t = max(0.0, min(1.0, t))
    return (
        p1[0] + t * (p2[0] - p1[0]),
        p1[1] + t * (p2[1] - p1[1]),
        p1[2] + t * (p2[2] - p1[2]),
    )

def polygonize_tet(pts, vals):
    b = 0
    if vals[0] <= 0: b |= 1
    if vals[1] <= 0: b |= 2
    if vals[2] <= 0: b |= 4
    if vals[3] <= 0: b |= 8

    if b == 0 or b == 15:
        return []

    p = pts
    v = vals

    def e(i, j):
        return interpolate(p[i], p[j], v[i], v[j])

    tris = []
    if b == 1:
        tris.append((e(0, 1), e(0, 2), e(0, 3)))
    elif b == 2:
        tris.append((e(1, 0), e(1, 3), e(1, 2)))
    elif b == 4:
        tris.append((e(2, 0), e(2, 1), e(2, 3)))
    elif b == 8:
        tris.append((e(3, 0), e(3, 2), e(3, 1)))
    elif b == 14: # 0 outside
        tris.append((e(0, 1), e(0, 3), e(0, 2)))
    elif b == 13: # 1 outside
        tris.append((e(1, 0), e(1, 2), e(1, 3)))
    elif b == 11: # 2 outside
        tris.append((e(2, 0), e(2, 3), e(2, 1)))
    elif b == 7:  # 3 outside
        tris.append((e(3, 0), e(3, 1), e(3, 2)))
    elif b == 3: # 0, 1 inside
        tris.append((e(0, 2), e(1, 2), e(1, 3)))
        tris.append((e(0, 2), e(1, 3), e(0, 3)))
    elif b == 5: # 0, 2 inside
        tris.append((e(0, 1), e(2, 1), e(2, 3)))
        tris.append((e(0, 1), e(2, 3), e(0, 3)))
    elif b == 6: # 1, 2 inside
        tris.append((e(1, 0), e(1, 3), e(2, 3)))
        tris.append((e(1, 0), e(2, 3), e(2, 0)))
    elif b == 9: # 0, 3 inside
        tris.append((e(0, 1), e(0, 2), e(3, 2)))
        tris.append((e(0, 1), e(3, 2), e(3, 1)))
    elif b == 10: # 1, 3 inside
        tris.append((e(1, 0), e(3, 0), e(3, 2)))
        tris.append((e(1, 0), e(3, 2), e(1, 2)))
    elif b == 12: # 2, 3 inside
        tris.append((e(2, 0), e(3, 0), e(3, 1)))
        tris.append((e(2, 0), e(3, 1), e(2, 1)))
    return tris

def write_stl(filename, triangles):
    with open(filename, 'wb') as f:
        header = b'Binary STL generated by Antigravity Mechanical Keyboard CAD'.ljust(80, b'\0')
        f.write(header)
        f.write(struct.pack('<I', len(triangles)))
        for tri in triangles:
            p1, p2, p3 = tri
            ax, ay, az = p2[0]-p1[0], p2[1]-p1[1], p2[2]-p1[2]
            bx, by, bz = p3[0]-p1[0], p3[1]-p1[1], p3[2]-p1[2]
            nx = ay*bz - az*by; ny = az*bx - ax*bz; nz = ax*by - ay*bx
            l = math.sqrt(nx*nx + ny*ny + nz*nz)
            if l > 1e-9: nx/=l; ny/=l; nz/=l
            else: nx, ny, nz = 0.0, 0.0, 1.0
            f.write(struct.pack('<3f', nx, ny, nz))
            f.write(struct.pack('<3f', *p1))
            f.write(struct.pack('<3f', *p2))
            f.write(struct.pack('<3f', *p3))
            f.write(struct.pack('<H', 0))

def sdf_box(x, y, z, bx, by, bz):
    dx = abs(x) - bx
    dy = abs(y) - by
    dz = abs(z) - bz
    mc_x = max(dx, 0.0); mc_y = max(dy, 0.0); mc_z = max(dz, 0.0)
    outside = math.sqrt(mc_x*mc_x + mc_y*mc_y + mc_z*mc_z)
    inside = min(max(dx, max(dy, dz)), 0.0)
    return outside + inside

def sdf_cylinder_z(x, y, z, r, hz):
    d_xy = math.sqrt(x*x + y*y) - r
    d_z = abs(z) - hz
    mc_xy = max(d_xy, 0.0); mc_z = max(d_z, 0.0)
    outside = math.sqrt(mc_xy*mc_xy + mc_z*mc_z)
    inside = min(max(d_xy, d_z), 0.0)
    return outside + inside

def generate_mesh_from_sdf(sdf_fn, x_range, y_range, z_range, step):
    x_min, x_max = x_range
    y_min, y_max = y_range
    z_min, z_max = z_range

    nx = int(math.ceil((x_max - x_min) / step)) + 1
    ny = int(math.ceil((y_max - y_min) / step)) + 1
    nz = int(math.ceil((z_max - z_min) / step)) + 1

    xs = [x_min + i * step for i in range(nx)]
    ys = [y_min + j * step for j in range(ny)]
    zs = [z_min + k * step for k in range(nz)]

    grid = [0.0] * (nx * ny * nz)
    idx = 0
    for k in range(nz):
        z = zs[k]
        for j in range(ny):
            y = ys[j]
            for i in range(nx):
                grid[idx] = sdf_fn(xs[i], y, z)
                idx += 1

    def gval(i, j, k):
        return grid[i + nx * (j + ny * k)]

    triangles = []
    for k in range(nz - 1):
        z0, z1 = zs[k], zs[k+1]
        for j in range(ny - 1):
            y0, y1 = ys[j], ys[j+1]
            for i in range(nx - 1):
                x0, x1 = xs[i], xs[i+1]
                
                c_vals = [
                    gval(i,   j,   k  ),
                    gval(i+1, j,   k  ),
                    gval(i+1, j+1, k  ),
                    gval(i,   j+1, k  ),
                    gval(i,   j,   k+1),
                    gval(i+1, j,   k+1),
                    gval(i+1, j+1, k+1),
                    gval(i,   j+1, k+1)
                ]
                if all(v > 0 for v in c_vals) or all(v <= 0 for v in c_vals):
                    continue

                c_pts = [
                    (x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0),
                    (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)
                ]

                tet_indices = [
                    (0, 5, 1, 6),
                    (0, 1, 2, 6),
                    (0, 2, 3, 6),
                    (0, 3, 7, 6),
                    (0, 7, 4, 6),
                    (0, 4, 5, 6)
                ]

                for t_idx in tet_indices:
                    t_pts = [c_pts[idx] for idx in t_idx]
                    t_vals = [c_vals[idx] for idx in t_idx]
                    triangles.extend(polygonize_tet(t_pts, t_vals))

    return triangles

