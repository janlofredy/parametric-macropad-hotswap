# 1. KAILH HOTSWAP CADDY SDF
# -------------------------------------------------------------
def kailh_caddy_sdf(x, y, z, with_tabs=True):
    z_rel = z - 2.4
    base = sdf_box(x, y, z_rel, 7.7 - 0.4, 7.7 - 0.4, 2.4 - 0.2) - 0.3
    
    if with_tabs:
        t1 = sdf_box(x - 9.4, y, z - 1.2, 2.2, 3.2, 1.2) - 0.3
        t2 = sdf_box(x + 9.4, y, z - 1.2, 2.2, 3.2, 1.2) - 0.3
        h1 = sdf_cylinder_z(x - 9.8, y, z - 1.2, 1.15, 2.0)
        h2 = sdf_cylinder_z(x + 9.8, y, z - 1.2, 1.15, 2.0)
        tabs = max(min(t1, t2), -min(h1, h2))
        base = min(base, tabs)
        
    top_pocket = sdf_box(x, y, z - 4.4, 7.05, 7.05, 0.6)
    center_hole = sdf_cylinder_z(x, y, z - 2.4, 2.2, 3.0)
    stab1 = sdf_cylinder_z(x - 5.08, y, z - 2.4, 1.05, 3.0)
    stab2 = sdf_cylinder_z(x + 5.08, y, z - 2.4, 1.05, 3.0)
    
    p1 = sdf_cylinder_z(x - (-3.81), y - 2.54, z - 2.4, 0.85, 3.0)
    p1_funnel = sdf_cylinder_z(x - (-3.81), y - 2.54, z - 4.4, 1.3, 0.6)
    p2 = sdf_cylinder_z(x - 2.54, y - 5.08, z - 2.4, 0.85, 3.0)
    p2_funnel = sdf_cylinder_z(x - 2.54, y - 5.08, z - 4.4, 1.3, 0.6)
    
    kailh_body = sdf_box(x + 0.3, y - 3.8, z - 1.5, 6.4, 2.8, 1.55)
    lug1 = sdf_box(x - (-6.0), y - 2.54, z - 1.2, 1.4, 1.6, 1.3)
    lug2 = sdf_box(x - 5.4, y - 5.08, z - 1.2, 1.4, 1.6, 1.3)
    
    row_wire = sdf_box(x, y - 2.54, z - 0.7, 12.0, 0.8, 0.75)
    col_wire = sdf_box(x - 5.8, y - 6.0, z - 0.7, 0.8, 3.0, 0.75)
    
    subtractions = min(
        top_pocket, center_hole, stab1, stab2,
        p1, p1_funnel, p2, p2_funnel,
        kailh_body, lug1, lug2,
        row_wire, col_wire
    )
    return max(base, -subtractions)

